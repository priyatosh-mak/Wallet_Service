-- Append-only history of wallet type assignments: close the current row, insert a new one. Never delete.
CREATE TABLE wallet_type_history (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id        INTEGER     NOT NULL REFERENCES wallets (id),
    wallet_type_id   INTEGER     NOT NULL REFERENCES wallet_types (id),
    effective_from   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    effective_to     TIMESTAMPTZ,
    superseded_by_id INTEGER REFERENCES wallet_type_history (id),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_wallet_type_history_range CHECK (effective_to IS NULL OR effective_to > effective_from)
);

CREATE INDEX idx_wallet_type_history_wallet_id ON wallet_type_history (wallet_id);
CREATE INDEX idx_wallet_type_history_wallet_type_id ON wallet_type_history (wallet_type_id);
-- At most one open (current) assignment per wallet.
CREATE UNIQUE INDEX uq_wallet_type_history_current ON wallet_type_history (wallet_id) WHERE effective_to IS NULL;

COMMENT ON COLUMN wallet_type_history.effective_to IS 'When the assignment ended; NULL means current.';
COMMENT ON COLUMN wallet_type_history.superseded_by_id IS 'Row that replaced this one after close + insert.';
