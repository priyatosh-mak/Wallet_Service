-- Transactional outbox: rows are inserted in the same transaction as the business change.
CREATE TABLE outbox_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       UUID         NOT NULL,
    event_type     VARCHAR(128) NOT NULL,
    aggregate_type VARCHAR(64)  NOT NULL,
    aggregate_id   VARCHAR(255) NOT NULL,
    partition_key  VARCHAR(255) NOT NULL,
    correlation_id VARCHAR(255),
    schema_version SMALLINT     NOT NULL DEFAULT 1,
    payload        JSONB        NOT NULL DEFAULT '{}',
    status         VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    attempt_count  INTEGER      NOT NULL DEFAULT 0,
    last_error     TEXT,
    next_retry_at  TIMESTAMPTZ,
    published_at   TIMESTAMPTZ,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_outbox_events_event_id UNIQUE (event_id),
    CONSTRAINT chk_outbox_events_status CHECK (status IN ('PENDING', 'PUBLISHED', 'DEAD')),
    CONSTRAINT chk_outbox_events_attempts_nonneg CHECK (attempt_count >= 0)
);

CREATE INDEX idx_outbox_events_pending ON outbox_events (status, next_retry_at, created_at) WHERE status = 'PENDING';
CREATE INDEX idx_outbox_events_aggregate ON outbox_events (aggregate_type, aggregate_id);

COMMENT ON COLUMN outbox_events.payload IS 'IDs and codes only. No names, phone numbers or account numbers.';
COMMENT ON COLUMN outbox_events.partition_key IS 'Kafka key; the wallet id so one wallet stays on one partition.';
COMMENT ON COLUMN outbox_events.status IS 'PENDING = not on Kafka yet, PUBLISHED = sent, DEAD = gave up (alert, do not auto-retry).';
