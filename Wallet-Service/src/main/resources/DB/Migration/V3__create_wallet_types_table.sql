-- Wallet type reference data. Default limits are copied onto a wallet when it is created.
CREATE TABLE wallet_types (
    id                                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                               VARCHAR(64)  NOT NULL,
    name                               VARCHAR(255) NOT NULL,
    description                        TEXT,
    default_credit_limit               NUMERIC(18, 2),
    can_extend_credit                  BOOLEAN      NOT NULL DEFAULT FALSE,
    default_disbursement_quota_limit   NUMERIC(18, 2),
    default_disbursement_quota_period  VARCHAR(16)  NOT NULL DEFAULT 'MONTHLY',
    default_general_transaction_limit  NUMERIC(18, 2),
    default_general_transaction_period VARCHAR(16)  NOT NULL DEFAULT 'DAILY',
    value_chain_category               VARCHAR(255),
    is_active                          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at                         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at                         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_wallet_types_code UNIQUE (code),
    CONSTRAINT chk_wallet_types_code_format CHECK (code ~ '^[A-Z][A-Z_]*$'),
    CONSTRAINT chk_wallet_types_quota_period CHECK (default_disbursement_quota_period IN ('WEEKLY', 'MONTHLY', 'YEARLY')),
    CONSTRAINT chk_wallet_types_transaction_period CHECK (default_general_transaction_period IN ('DAILY', 'WEEKLY', 'MONTHLY')),
    CONSTRAINT chk_wallet_types_limits_nonneg CHECK (
        COALESCE(default_credit_limit, 0) >= 0
        AND COALESCE(default_disbursement_quota_limit, 0) >= 0
        AND COALESCE(default_general_transaction_limit, 0) >= 0)
);

COMMENT ON COLUMN wallet_types.can_extend_credit IS 'TRUE: the type may grant credit to others, so a disbursement quota applies.';
COMMENT ON COLUMN wallet_types.default_credit_limit IS 'Default pooled credit ceiling for loan/credit requests; not cash-in/out/P2P.';
COMMENT ON COLUMN wallet_types.default_general_transaction_limit IS 'Default cash-in, cash-out and P2P ceiling per period.';
