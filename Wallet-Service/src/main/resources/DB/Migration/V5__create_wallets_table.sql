-- A wallet belongs to exactly one subject: a customer (user_id) or a business (business_public_uuid).
CREATE TABLE wallets (
    id                         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                    INTEGER,
    business_public_uuid       UUID,
    wallet_type_id             INTEGER        NOT NULL REFERENCES wallet_types (id),
    currency_id                INTEGER        NOT NULL REFERENCES currencies (id),
    balance                    NUMERIC(18, 2) NOT NULL DEFAULT 0,
    credit_limit               NUMERIC(18, 2) NOT NULL DEFAULT 0,
    pin_dashboard              BOOLEAN        NOT NULL DEFAULT TRUE,
    is_active                  BOOLEAN        NOT NULL DEFAULT FALSE,
    verified_at                TIMESTAMPTZ,
    general_transaction_limit  NUMERIC(18, 2),
    general_transaction_period VARCHAR(16)    NOT NULL DEFAULT 'DAILY',
    disbursement_quota_limit   NUMERIC(18, 2) NOT NULL DEFAULT 0,
    disbursement_quota_used    NUMERIC(18, 2) NOT NULL DEFAULT 0,
    disbursement_quota_period  VARCHAR(16)    NOT NULL DEFAULT 'MONTHLY',
    created_at                 TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at                 TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_wallets_one_subject CHECK ((user_id IS NOT NULL) <> (business_public_uuid IS NOT NULL)),
    CONSTRAINT chk_wallets_credit_limit_nonneg CHECK (credit_limit >= 0),
    CONSTRAINT chk_wallets_transaction_limit_nonneg CHECK (general_transaction_limit IS NULL OR general_transaction_limit >= 0),
    CONSTRAINT chk_wallets_transaction_period CHECK (general_transaction_period IN ('DAILY', 'WEEKLY', 'MONTHLY')),
    CONSTRAINT chk_wallets_quota_period CHECK (disbursement_quota_period IN ('WEEKLY', 'MONTHLY', 'YEARLY')),
    CONSTRAINT chk_wallets_quota_used_nonneg CHECK (disbursement_quota_used >= 0),
    CONSTRAINT chk_wallets_quota_used_le_limit CHECK (disbursement_quota_used <= disbursement_quota_limit),
    CONSTRAINT chk_wallets_verified_when_active CHECK (is_active = FALSE OR verified_at IS NOT NULL)
);

-- Duplicate-ownership guards: one wallet per customer, one wallet per business.
CREATE UNIQUE INDEX uq_wallets_user_id ON wallets (user_id) WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX uq_wallets_business_public_uuid ON wallets (business_public_uuid) WHERE business_public_uuid IS NOT NULL;
CREATE INDEX idx_wallets_wallet_type_id ON wallets (wallet_type_id);
CREATE INDEX idx_wallets_currency_id ON wallets (currency_id);

COMMENT ON COLUMN wallets.user_id IS 'Direct customer (logical FK to the auth service user id). NULL for business wallets.';
COMMENT ON COLUMN wallets.business_public_uuid IS 'Business subject. NULL for customer wallets.';
COMMENT ON COLUMN wallets.wallet_type_id IS 'Current wallet type (cache); the full history is in wallet_type_history.';
COMMENT ON COLUMN wallets.balance IS 'Spendable balance cache. Only the posting engine may change it.';
COMMENT ON COLUMN wallets.verified_at IS 'Set on first activation after approval. Suspension clears is_active but keeps this timestamp.';
COMMENT ON COLUMN wallets.disbursement_quota_limit IS 'Quota for the current window; 0 when the wallet type cannot extend credit.';
