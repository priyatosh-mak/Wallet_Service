-- Currency reference data. Currencies are never deleted, only deactivated.
CREATE TABLE currencies (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(3)   NOT NULL,
    name        VARCHAR(100) NOT NULL,
    minor_units SMALLINT     NOT NULL DEFAULT 2,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_currencies_code UNIQUE (code),
    CONSTRAINT chk_currencies_code_format CHECK (code ~ '^[A-Z]{3}$'),
    CONSTRAINT chk_currencies_minor_units CHECK (minor_units BETWEEN 0 AND 6)
);

COMMENT ON COLUMN currencies.code IS 'ISO 4217 alphabetic code, upper case.';
COMMENT ON COLUMN currencies.minor_units IS 'Decimal places of the currency (usually 2).';
